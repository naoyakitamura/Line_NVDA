"""Notify Discord only after public release assets and their hashes verify."""
import hashlib
import io
import json
import os
import re
import urllib.request
from zipfile import ZipFile


def fetch(url):
    request=urllib.request.Request(url,headers={'User-Agent':'Line-NVDA-release-check'})
    with urllib.request.urlopen(request,timeout=60) as response:
        data=response.read(20*1024*1024+1)
    if len(data)>20*1024*1024:raise ValueError('Asset exceeds verification limit')
    return data


def verify_and_message(repo,release,download=fetch):
    if not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+',repo):raise ValueError('Invalid repository')
    tag=release['tag_name']
    if not re.fullmatch(r'v\d+\.\d+\.\d+',tag) or release.get('draft'):raise ValueError('Not a published version')
    version=tag[1:]
    base=f'https://github.com/{repo}/releases/download/{tag}/'
    targets=('2025.3jp','2026.2jp')
    names=[f'lineAccessibility-{version}-nvda{target}.nvda-addon' for target in targets]
    bundle=f'lineAccessibility-{version}-trial.zip'
    assets={item['name']:item for item in release['assets']}
    for name in names+[bundle,'SHA256SUMS.txt']:
        if name not in assets or assets[name]['browser_download_url']!=base+name or assets[name]['state']!='uploaded':
            raise ValueError('Required asset is missing or not uploaded')
    sums={name:digest for digest,name in (line.split('  ',1) for line in download(base+'SHA256SUMS.txt').decode('utf-8').splitlines())}
    payloads={}
    for name in names+[bundle]:
        data=download(base+name)
        if hashlib.sha256(data).hexdigest()!=sums.get(name):raise ValueError('Asset checksum mismatch')
        payloads[name]=data
    for name in names:
        with ZipFile(io.BytesIO(payloads[name])) as z:
            manifest=z.read('manifest.ini').decode('utf-8')
            if not re.search(r'^version = '+re.escape(version)+r'\s*$',manifest,re.M):raise ValueError('Addon version mismatch')
            if 'minimumNVDAVersion = 2025.3' not in manifest:raise ValueError('Expected shared compatibility build')
    if payloads[names[0]]!=payloads[names[1]]:raise ValueError('Expected identical shared builds')
    with ZipFile(io.BytesIO(payloads[bundle])) as z:
        prefix=f'lineAccessibility-{version}-trial/'
        z.getinfo(prefix+'SOURCE.zip')
        if z.read(prefix+f'lineAccessibility-{version}.nvda-addon')!=payloads[names[0]]:raise ValueError('Bundle differs from addon')
    body=release.get('body') or ''
    # Release notes generated by prepare_publication.py or the documented Markdown form.
    change_block=re.split(r'(?:## )?ダウンロード',body,maxsplit=1)[0].strip()
    if not change_block:raise ValueError('Release notes are missing')
    if len(change_block)>700:change_block=change_block[:700]+'\n（詳細はリリースページをご覧ください）'
    text=f'LINE読み上げ補助 {version} 更新のお知らせ\n\n{change_block}\n\n'
    text+='\n'.join(f'NVDA {target}用：\n{base}{name}' for target,name in zip(targets,names))
    text+=f'\n\n説明書・ソース付きZIP：\n{base}{bundle}\n\n詳細：\nhttps://github.com/{repo}/releases/tag/{tag}'
    text+='\n\nインストール後はNVDAを再起動してください。2025.3jp本体での実操作は未確認の試用版です。'
    if len(text)>2000:raise ValueError('Discord message is too long')
    return {'content':text,'allowed_mentions':{'parse':[]}}


def main():
    webhook=os.environ.get('DISCORD_WEBHOOK_URL','')
    if not re.fullmatch(r'https://discord\.com/api/webhooks/[0-9]+/[A-Za-z0-9._-]+',webhook):
        raise ValueError('Discord webhook secret is missing or invalid')
    with open(os.environ['GITHUB_EVENT_PATH'],encoding='utf-8') as f:event=json.load(f)
    payload=verify_and_message(os.environ['GITHUB_REPOSITORY'],event['release'])
    request=urllib.request.Request(webhook+'?wait=true',data=json.dumps(payload,ensure_ascii=False).encode('utf-8'),headers={'Content-Type':'application/json','User-Agent':'Line-NVDA-release-notifier'},method='POST')
    with urllib.request.urlopen(request,timeout=30) as response:
        message=json.load(response)
    if not message.get('id'):raise ValueError('Discord did not confirm a message')
    print('Discord notification confirmed.')


if __name__=='__main__':
    try:main()
    except Exception as error:
        # Never put a webhook URL or token into CI output, including error URLs.
        print('Publication notification failed: '+type(error).__name__)
        raise SystemExit(1)

